import type { Blueprint, RoleSpec } from './types';

/**
 * Committee presets per product category, sized for a 51-500 person account.
 * `adaptForSize` (size.ts) collapses them for small companies and adds review roles
 * for large ones.
 *
 * Roles are deliberately separated by seniority (economic buyer above champion above
 * evaluator) so that the same person rarely matches two roles.
 */

const WHY = {
  economicBuyer: 'Owns the budget and makes the final call.',
  champion: 'Feels the problem day to day and will sell the purchase internally.',
  technicalEvaluator: 'Runs the trial and checks how it fits the existing stack.',
  endUserLead: 'Leads the team that will use it every day; adoption depends on them.',
};

function economicBuyer(label: string, department: RoleSpec['department']): RoleSpec {
  return {
    key: 'economic-buyer',
    label: `Economic buyer (${label})`,
    why: WHY.economicBuyer,
    department,
    seniority: ['c-suite', 'vp', 'head'],
    position: [],
    limit: 1,
    priority: 1,
  };
}

